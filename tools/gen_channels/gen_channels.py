#!/usr/bin/env python3
"""Generate the channel-table bindings from spec/telemetry-shm/channels/*.json.

    uv run tools/gen_channels/gen_channels.py            # write the files
    uv run tools/gen_channels/gen_channels.py --check    # exit 1 if a file differs

Standard library only. Output is deterministic (LF line endings, JSON order) and
committed; CI runs --check so the committed headers cannot drift from the JSON.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPEC = ROOT / "spec" / "telemetry-shm" / "channels"
CPP_OUT = ROOT / "bindings" / "cpp" / "include" / "irtactile" / "telemetry"
CS_OUT = ROOT / "bindings" / "csharp" / "src" / "IrTactile.Shm" / "Telemetry"

LAYOUTS = {"index": "Index", "wheel": "Wheel", "axle": "Axle"}
CPP_NS = {"std": "standard"}  # `namespace std` would shadow ::std inside irt::telemetry
CS_CLASS = {"std": "Std"}
KINDS = {"continuous": "Continuous", "discrete": "Discrete", "event": "Event"}
NAME_MAX = 63
HEADER_NOTE = "GENERATED by tools/gen_channels/gen_channels.py from spec/telemetry-shm/channels/{src}. Do not edit."


def ident(name: str, namespace: str) -> str:
    """core.suspension.deflection.FL -> SuspensionDeflectionFL."""
    assert name.startswith(namespace + ".")
    parts = re.split(r"[._]", name[len(namespace) + 1:])
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def f(v: float) -> str:
    s = repr(float(v))
    if "." not in s and "e" not in s:
        s += ".0"
    return s


def load(ns: str) -> dict:
    data = json.loads((SPEC / f"{ns}.json").read_text(encoding="utf-8"))
    assert data["schema"] == 1 and data["namespace"] == ns
    seen: set[str] = set()
    for c in data["channels"] + data.get("arrays", []):
        assert c["name"].startswith(ns + "."), c["name"]
        assert len(c["name"]) <= NAME_MAX, c["name"]
        assert c["kind"] in KINDS, c["name"]
        assert c["name"] not in seen, f"duplicate {c['name']}"
        seen.add(c["name"])
    for c in data["channels"]:
        assert "layout" not in c, f"scalar {c['name']} must not declare a layout"
    for a in data.get("arrays", []):
        assert a["layout"] in LAYOUTS, a["name"]
        assert 1 <= a["capacity"] <= 65535, a["name"]
    for group in (data["channels"], data.get("arrays", [])):
        ids = [ident(c["name"], ns) for c in group]
        assert len(ids) == len(set(ids)), "identifier collision in " + ns
    return data


def cpp_entry(c: dict, flags: str, cap: int) -> str:
    layout = LAYOUTS[c.get("layout", "index")]
    return (f'    {{"{c["name"]}", "{c["unit"]}", {f(c["min"])}f, {f(c["max"])}f, '
            f'Kind::{KINDS[c["kind"]]}, {flags}, {cap}, ArrayLayout::{layout}}},')


def cpp_enum(name: str, e: dict) -> list[str]:
    out = [f"/// {e['doc']}", f"enum class {name} : uint32_t {{"]
    for k, v in e["values"].items():
        out.append(f"    {k} = {v},")
    out.append("};")
    if "reserved" in e:
        lo, hi = e["reserved"]
        out.append(f"inline constexpr uint32_t k{name}ReservedFirst = {lo};")
        out.append(f"inline constexpr uint32_t k{name}ReservedLast  = {hi};")
    return out


def gen_cpp(ns: str, d: dict) -> str:
    chans = d["channels"]
    arrays = d.get("arrays", [])
    flags = "kFlagOptional"  # every std.* channel is optional (availability = registration)
    L = [
        f"// irtactile/telemetry/{ns}_channels.h - {ns}.* channel table.",
        "//",
        "// SPDX-License-Identifier: MIT",
        f"// {HEADER_NOTE.format(src=ns + '.json')}",
        "",
        f"#ifndef IRTACTILE_TELEMETRY_{ns.upper()}_CHANNELS_H",
        f"#define IRTACTILE_TELEMETRY_{ns.upper()}_CHANNELS_H",
        "",
        "#include <cstdint>",
        "",
        "#include <irtactile/telemetry/channel_model.h>",
        "",
        "namespace irt {",
        "namespace telemetry {",
        f"namespace {CPP_NS.get(ns, ns)} {{",
        "",
        "/// Position of the channel in kChannels. A writer handle, not a bus slot.",
        "enum class Id : uint32_t {",
    ]
    for c in chans:
        L.append(f"    {ident(c['name'], ns)},")
    L += ["};", "", f"inline constexpr uint32_t kCount = {len(chans)};", "",
          "inline constexpr ChannelDef kChannels[kCount] = {"]
    for c in chans:
        L.append(cpp_entry(c, flags, 0))
    L += ["};", ""]
    if arrays:
        L += ["/// Array tables: `name` is the base name, elements are `name[0..arrayCapacity)`.",
              "enum class ArrayId : uint32_t {"]
        for a in arrays:
            L.append(f"    {ident(a['name'], ns)},")
        L += ["};", "", f"inline constexpr uint32_t kArrayCount = {len(arrays)};", "",
              "inline constexpr ChannelDef kArrays[kArrayCount] = {"]
        for a in arrays:
            L.append(cpp_entry(a, flags, a["capacity"]))
        L += ["};", ""]
    for en, e in d.get("enums", {}).items():
        L += cpp_enum(en, e) + [""]
    L += [f"}}  // namespace {CPP_NS.get(ns, ns)}", "}  // namespace telemetry", "}  // namespace irt", "",
          f"#endif  // IRTACTILE_TELEMETRY_{ns.upper()}_CHANNELS_H", ""]
    return "\n".join(L)


def gen_cs(ns: str, d: dict) -> str:
    chans = d["channels"]
    arrays = d.get("arrays", [])
    flags = "ChannelFlags.Optional"
    cls = CS_CLASS.get(ns, ns.capitalize() + "Channels")
    L = [
        "// SPDX-License-Identifier: MIT",
        f"// {HEADER_NOTE.format(src=ns + '.json')}",
        "",
        "namespace IrTactile.Shm.Telemetry;",
        "",
        f"/// <summary>Position of the channel in <see cref=\"{cls}.All\"/>.</summary>",
        f"public enum {ns.capitalize()}Channel : uint",
        "{",
    ]
    for c in chans:
        L.append(f"    {ident(c['name'], ns)},")
    L += ["}", ""]
    if arrays:
        L += [f"public enum {ns.capitalize()}Array : uint", "{"]
        for a in arrays:
            L.append(f"    {ident(a['name'], ns)},")
        L += ["}", ""]
    for en, e in d.get("enums", {}).items():
        L += [f"/// <summary>{e['doc']}</summary>", f"public enum {en} : uint", "{"]
        for k, v in e["values"].items():
            L.append(f"    {k} = {v},")
        L += ["}", ""]

    def cs_entry(c: dict, cap: int) -> str:
        layout = LAYOUTS[c.get("layout", "index")]
        return (f'        new("{c["name"]}", "{c["unit"]}", {f(c["min"])}f, {f(c["max"])}f, '
                f'SignalKind.{KINDS[c["kind"]]}, {flags}, {cap}, ArrayLayout.{layout}),')

    L += [f"public static class {cls}", "{",
          "    public static readonly ChannelDef[] All =",
          "    {"]
    L += [cs_entry(c, 0) for c in chans]
    L += ["    };"]
    if arrays:
        L += ["", "    /// <summary>Base names; elements are <c>name[0..ArrayCapacity)</c>.</summary>",
              "    public static readonly ChannelDef[] Arrays =", "    {"]
        L += [cs_entry(a, a["capacity"]) for a in arrays]
        L += ["    };"]
    L += ["}", ""]
    return "\n".join(L)


def outputs() -> dict[Path, str]:
    std = load("std")
    return {
        CPP_OUT / "std_channels.h": gen_cpp("std", std),
        CS_OUT / "StdChannels.g.cs": gen_cs("std", std),
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if a generated file differs")
    args = ap.parse_args()
    bad = 0
    for path, text in outputs().items():
        if args.check:
            have = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
            if have != text:
                print(f"OUT OF DATE: {path.relative_to(ROOT)}", file=sys.stderr)
                bad += 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
